@pytest.mark.parametrize("unique", [False, True])
def test_added_indexed_column_creates_index_once(monkeypatch, unique) -> None:
    engine = create_engine("sqlite://")
    metadata = MetaData()
    table = Table(
        "countries", metadata,
        Column("id", Integer, primary_key=True),
        Column("is_active", Boolean, index=True, unique=unique),
    )
    monkeypatch.setattr(migrations_mod, "_load_model_metadata", lambda: None)
    monkeypatch.setattr(migrations_mod, "SQLModel", SimpleNamespace(metadata=metadata))
    try:
        with engine.begin() as connection:
            Table(
                "countries", MetaData(), Column("id", Integer, primary_key=True)
            ).create(connection)
            migrations_mod._apply_model_schema_changes(connection)
            migrations_mod._apply_model_schema_changes(connection)
            indexes = inspect(connection).get_indexes("countries")
            assert len(indexes) == 1
            assert indexes[0]["name"] == "ix_countries_is_active"
            assert bool(indexes[0]["unique"]) is unique
            assert table.c.is_active.index is True
            assert table.c.is_active.unique is unique
    finally:
        engine.dispose()



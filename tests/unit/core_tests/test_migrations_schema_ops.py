def test_ordered_schema_operations_drops_index_before_create() -> None:
    """Same-name index replacement: DropIndex must precede CreateIndex."""
    create = ops.CreateIndexOp(
        "uq_academic_interests_major_minor_name",
        "academic_interests",
        ["major_id", "minor_id", "name"],
        unique=True,
    )
    drop = ops.DropIndexOp(
        "uq_academic_interests_major_minor_name",
        table_name="academic_interests",
    )
    # Autogenerate may list create before drop depending on flatten order;
    # our sorter must still drop first.
    ordered = [op for _, op in migrations_mod._ordered_schema_operations([create, drop])]
    assert isinstance(ordered[0], ops.DropIndexOp)
    assert isinstance(ordered[1], ops.CreateIndexOp)
    assert ordered[0].index_name == "uq_academic_interests_major_minor_name"
    assert ordered[1].index_name == "uq_academic_interests_major_minor_name"


def test_ordered_schema_operations_preserves_relative_order_within_priority() -> None:
    drop_a = ops.DropIndexOp("ix_a", table_name="t")
    drop_b = ops.DropIndexOp("ix_b", table_name="t")
    ordered = [op for _, op in migrations_mod._ordered_schema_operations([drop_a, drop_b])]
    assert [op.index_name for op in ordered] == ["ix_a", "ix_b"]


def test_apply_model_schema_changes_invokes_drop_then_create(monkeypatch) -> None:
    """Simulates lower(name) -> name replacement for the same index name."""
    metadata = MetaData()
    table = Table(
        "academic_interests",
        metadata,
        Column("id", Integer, primary_key=True),
        Column("major_id", Integer),
        Column("minor_id", Integer),
        Column("name", String(100)),
    )
    # New model definition: plain name column (not lower(name)).
    Index(
        "uq_academic_interests_major_minor_name",
        table.c.major_id,
        table.c.minor_id,
        table.c.name,
        unique=True,
        postgresql_where=text("major_id IS NOT NULL AND minor_id IS NOT NULL"),
    )

    drop = ops.DropIndexOp(
        "uq_academic_interests_major_minor_name",
        table_name="academic_interests",
    )
    create = ops.CreateIndexOp(
        "uq_academic_interests_major_minor_name",
        "academic_interests",
        ["major_id", "minor_id", "name"],
        unique=True,
    )
    # Intentionally create-before-drop to prove ordering fix.
    upgrade_ops = ops.UpgradeOps(ops=[create, drop])

    monkeypatch.setattr(migrations_mod, "_load_model_metadata", lambda: None)
    monkeypatch.setattr(
        migrations_mod,
        "MigrationContext",
        SimpleNamespace(
            configure=lambda *_a, **_k: MagicMock(name="migration_context"),
        ),
    )
    monkeypatch.setattr(
        migrations_mod,
        "produce_migrations",
        lambda *_a, **_k: SimpleNamespace(upgrade_ops=upgrade_ops),
    )
    monkeypatch.setattr(migrations_mod, "SQLModel", SimpleNamespace(metadata=metadata))

    invoked: list[object] = []

    class _FakeOperations:
        def __init__(self, *_a, **_k) -> None:
            pass

        def invoke(self, operation) -> None:
            invoked.append(operation)

    monkeypatch.setattr(migrations_mod, "Operations", _FakeOperations)

    migrations_mod._apply_model_schema_changes(MagicMock(name="connection"))

    assert len(invoked) == 2
    assert isinstance(invoked[0], ops.DropIndexOp)
    assert isinstance(invoked[1], ops.CreateIndexOp)
    assert invoked[0].index_name == "uq_academic_interests_major_minor_name"
    assert invoked[1].index_name == "uq_academic_interests_major_minor_name"



def test_expression_index_diff_helpers_distinguish_lower_vs_name() -> None:
    """Document the failure mode: DB had lower(name), model has name."""
    old_expr = str(func.lower(column("name")))
    new_expr = "name"
    assert "lower" in old_expr.lower()
    assert new_expr == "name"
    assert old_expr.lower() != new_expr.lower()

def _flatten_upgrade_ops(operation) -> list:
    if isinstance(operation, (ops.UpgradeOps, ops.ModifyTableOps)):
        flattened = []
        for child_operation in operation.ops:
            flattened.extend(_flatten_upgrade_ops(child_operation))
        return flattened
    return [operation]


def _can_apply_autogenerated_operation(operation) -> bool:
    return isinstance(
        operation,
        (
            ops.AddColumnOp,
            ops.AlterColumnOp,
            ops.CreateIndexOp,
            ops.CreateTableOp,
            ops.CreateUniqueConstraintOp,
            ops.CreateForeignKeyOp,
            ops.CreateCheckConstraintOp,
            ops.DropColumnOp,
            ops.DropTableOp,
            ops.ModifyTableOps,
        ),
    )


def _compare_server_default(
    _context,
    inspected_column,
    metadata_column,
    _rendered_inspected_default,
    _metadata_default,
    _rendered_metadata_default,
):
    json_types = (SQLAlchemyJSON, JSON, JSONB)
    if isinstance(inspected_column.type, json_types) or isinstance(
        metadata_column.type,
        json_types,
    ):
        return False
    return None


def _prepare_autogenerated_operation(operation) -> None:
    if not isinstance(operation, ops.AlterColumnOp):
        return
    if not isinstance(operation.modify_type, SQLAlchemyEnum):
        return
    if "postgresql_using" in operation.kw:
        return

    column_name = operation.column_name
    enum_name = operation.modify_type.name
    if not enum_name:
        return

    operation.kw["postgresql_using"] = f"{column_name}::{enum_name}"


def _apply_model_schema_changes(connection: Connection) -> None:
    _load_model_metadata()
    migration_context = MigrationContext.configure(
        connection,
        opts={
            "compare_type": True,
            "compare_server_default": _compare_server_default,
            "target_metadata": SQLModel.metadata,
        },
    )
    migration_script = produce_migrations(migration_context, SQLModel.metadata)
    operations = _flatten_upgrade_ops(migration_script.upgrade_ops)
    if not operations:
        logger.info("No model schema changes detected by Alembic.")
        return

    alembic_operations = Operations(migration_context)
    for operation in operations:
        if not _can_apply_autogenerated_operation(operation):
            logger.warning(
                "Skipping unsupported autogenerated Alembic operation",
                extra={"operation": repr(operation)},
            )
            continue

        logger.info(
            "Applying autogenerated Alembic operation",
            extra={"operation": repr(operation)},
        )
        _prepare_autogenerated_operation(operation)
        alembic_operations.invoke(operation)


def _truncate_alembic_version(connection: Connection) -> None:
    has_version_table = connection.execute(
        text("SELECT to_regclass('public.alembic_version')")
    ).scalar_one()
    if has_version_table is None:
        return

    logger.warning("Truncating alembic_version table before startup migration.")
    connection.execute(text("TRUNCATE TABLE alembic_version"))



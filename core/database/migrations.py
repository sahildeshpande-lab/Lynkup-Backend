def _prepare_database(connection: Connection) -> None:
    connection.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))


def _upgrade_to_head_with_lock(connection: Connection) -> None:
    connection.execute(
        text(f"SELECT pg_advisory_xact_lock({ALEMBIC_ADVISORY_LOCK_KEY})")
    )
    _prepare_database(connection)
    _clear_orphaned_version_rows(connection)
    _upgrade_to_head(connection)


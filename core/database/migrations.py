def _prepare_database(connection):
    logger.info("Creating pg_trgm extension")
    connection.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))
    logger.info("pg_trgm extension ready")


def _upgrade_to_head_with_lock(connection: Connection) -> None:
    connection.execute(
        text(f"SELECT pg_advisory_xact_lock({ALEMBIC_ADVISORY_LOCK_KEY})")
    )
    _prepare_database(connection)
    _truncate_alembic_version(connection)
    _upgrade_to_head(connection)
    _apply_model_schema_changes(connection)

def _upgrade_to_head_with_managed_connection() -> None:
    connectable = create_engine(
        db_settings.database_url,
        poolclass=NullPool,
        future=True,
    )
    try:
        with connectable.begin() as connection:
            _upgrade_to_head_with_lock(connection)
    finally:
        connectable.dispose()


async def run_db_migrations_programmatically(
    connection: AsyncConnection | None = None,
) -> None:
    """
    Run Alembic migrations from application startup.

    When an async connection is provided, Alembic is run on its sync adapter so
    the migration command can share the caller's transaction. Otherwise the
    synchronous Alembic command is moved off the event loop.
    """
    if connection is not None:
        await connection.run_sync(_upgrade_to_head_with_lock)
        return

    await asyncio.to_thread(_upgrade_to_head_with_managed_connection)


async def run_db_migrations(connection: AsyncConnection | None = None) -> None:
    await run_db_migrations_programmatically(connection=connection)


if __name__ == "__main__":
    asyncio.run(run_db_migrations_programmatically())

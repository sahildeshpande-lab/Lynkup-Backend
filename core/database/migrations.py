logger = logging.getLogger(__name__)

ALEMBIC_ADVISORY_LOCK_KEY = 742893472
ADVISORY_LOCK_KEY = ALEMBIC_ADVISORY_LOCK_KEY
PROJECT_ROOT = Path(__file__).resolve().parents[2]
ALEMBIC_INI_PATH = PROJECT_ROOT / "alembic.ini"
ALEMBIC_VERSIONS_PATH = PROJECT_ROOT / "alembic" / "versions"


def build_alembic_config() -> Config:
    """Build Alembic config with runtime database settings."""
    cfg = Config(str(ALEMBIC_INI_PATH))
    cfg.set_main_option("sqlalchemy.url", db_settings.database_url)
    return cfg


def _upgrade_to_head(connection: Connection | None = None) -> None:
    cfg = build_alembic_config()
    if connection is not None:
        cfg.attributes["connection"] = connection

    # _generate_revision_if_needed(cfg)
    logger.info("Running Alembic migrations to head.")
    command.upgrade(cfg, "head")
    logger.info("Alembic migrations complete.")



def _has_local_revision_files() -> bool:
    return any(
        path.is_file() and path.suffix == ".py" and path.name != "__init__.py"
        for path in ALEMBIC_VERSIONS_PATH.glob("*.py")
    )


def _clear_orphaned_version_rows(connection: Connection) -> None:
    if _has_local_revision_files():
        return

    connection.execute(
        text(
            """
            DO $$
            BEGIN
                IF to_regclass('public.alembic_version') IS NOT NULL THEN
                    DELETE FROM alembic_version;
                END IF;
            END $$;
            """
        )
    )


